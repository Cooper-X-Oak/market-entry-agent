import { cp, mkdir, readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { createHash } from 'node:crypto';
import path from 'node:path';
const root = process.cwd();
if (!root.endsWith('/.grok/verify-artifacts/a10-remote-20260908')) throw new Error('Only the isolated remote acceptance directory is allowed');
const require = createRequire(path.join(root, 'packages/database/package.json'));
const entry = require.resolve('postgres');
const source = path.resolve(path.dirname(entry), entry.includes('/cjs/') ? '../..' : '..');
const pkg = JSON.parse(await readFile(path.join(source, 'package.json'), 'utf8'));
if (pkg.version !== '3.4.9') throw new Error('PostgreSQL driver version drift');
const destination = path.join(root, '.test-dependencies/postgres');
await mkdir(path.dirname(destination), { recursive: true });
await cp(source, destination, { recursive: true });
const filename = path.join(destination, 'src/connection.js');
const original = await readFile(filename, 'utf8');
const before = "    if (stream)\n      return queryError(q, Errors.generic('COPY_IN_PROGRESS'";
if (original.split(before).length !== 2) throw new Error('Driver patch context drift');
const closedMarker = "    closedTime = performance.now()";
if (original.split(closedMarker).length !== 2) throw new Error('Driver close patch context drift');
const patched = original.replace(before, "    if (!socket || socket.destroyed) {\n      queryError(q, Errors.connection('CONNECTION_CLOSED', options, socket))\n      return true\n    }\n\n" + before).replace(closedMarker, "    query = null\n" + closedMarker);
await writeFile(filename, patched);
await writeFile(path.join(root, 'postgres-patch-verification.json'), JSON.stringify({ version: pkg.version, runtime: 'ESM', sourceFile: path.join(source, 'src/connection.js'), originalSha256: createHash('sha256').update(original).digest('hex'), patchedSha256: createHash('sha256').update(patched).digest('hex') }, null, 2));
